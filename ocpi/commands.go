// CommandAckResult is the result field of a CommandAck.
type CommandAckResult string

const (
	CommandAckAccepted       CommandAckResult = "ACCEPTED"
	CommandAckRejected       CommandAckResult = "REJECTED"
	CommandAckNotSupported   CommandAckResult = "NOT_SUPPORTED"
	CommandAckUnknownSession CommandAckResult = "UNKNOWN_SESSION"
)

// CommandAck is the ACK returned directly as `data` of
// POST /commands/{command_type} — the immediate response from the target
// CPO, forwarded by the Hub as-is (not wrapped in another object).
type CommandAck struct {
	Result  CommandAckResult `json:"result"`
	Timeout int              `json:"timeout"`
	Message map[string]any   `json:"message,omitempty"`
}

// CommandFinalResult is the asynchronous, final outcome of a Command,
// reported by the target CPO via POST /commands/callback/{command_id}
// (or forced to TIMEOUT by GetCommand after 30s with no response).
type CommandFinalResult string

const (
	CommandFinalAccepted           CommandFinalResult = "ACCEPTED"
	CommandFinalRejected           CommandFinalResult = "REJECTED"
	CommandFinalFailed             CommandFinalResult = "FAILED"
	CommandFinalTimeout            CommandFinalResult = "TIMEOUT"
	CommandFinalUnknownReservation CommandFinalResult = "UNKNOWN_RESERVATION"
)

// Command is the response shape of GET /commands/callback/{command_id}.
type Command struct {
	ID                    string             `json:"id"`
	Type                  string             `json:"type"`
	Payload               any                `json:"payload"`
	AckResult             CommandAckResult   `json:"ack_result,omitempty"`
	AckMessage            map[string]any     `json:"ack_message,omitempty"`
	FinalResult           CommandFinalResult `json:"final_result,omitempty"`
	FinalResultReceivedAt string             `json:"final_result_received_at,omitempty"`
	LastUpdated           string             `json:"last_updated"`
}

// CommandAckResponse is the full envelope returned by
// POST /commands/{command_type}.
type CommandAckResponse = Envelope[CommandAck]

// CommandResponse is the full envelope returned by
// GET /commands/callback/{command_id}.
type CommandResponse = Envelope[Command]

// StartSession sends a remote START_SESSION command to the CPO that owns
// cmd.LocationID, via POST /commands/START_SESSION. Requires an EMSP role.
func (c *Client) StartSession(ctx context.Context, tokenB string, cmd StartSessionCommand) (*CommandAckResponse, error) {
	url := c.baseURL + "/commands/START_SESSION"
	return doRequest[CommandAck](ctx, c, http.MethodPost, url, tokenB, cmd)
}

