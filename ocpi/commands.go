// GetCommand calls GET /commands/callback/{command_id} to fetch the current
// state of a previously-sent Command. Any CONNECTED connection may call
// this. If more than 30s have elapsed without a callback, the Hub marks
// the command TIMEOUT automatically before returning.
func (c *Client) GetCommand(ctx context.Context, tokenB, commandID string) (*CommandResponse, error) {
	url := c.baseURL + "/commands/callback/" + commandID
	return doRequest[Command](ctx, c, http.MethodGet, url, tokenB, nil)
}
